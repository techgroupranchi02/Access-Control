  const leadToken = await login('lead@demo.com');
  const reviewerToken = await login('reviewer@demo.com');
  const juryToken = await login('jury@demo.com');
  const viewerToken = await login('viewer@demo.com');

  const meAdmin = await fetch(base + '/auth/me?editionId=1', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const meLead = await fetch(base + '/auth/me?editionId=1', { headers: { Authorization: 'Bearer ' + leadToken, 'X-Edition-Id': '1' } }).then(r => r.json());
