  const meViewer = await fetch(base + '/auth/me?editionId=1', { headers: { Authorization: 'Bearer ' + viewerToken, 'X-Edition-Id': '1' } }).then(r => r.json());

  const events = await fetch(base + '/events', { headers: { Authorization: 'Bearer ' + adminToken } }).then(r => r.json());
  const eventConfig = await fetch(base + '/events/1/config', { headers: { Authorization: 'Bearer ' + adminToken } }).then(r => r.json());
  const groups = await fetch(base + '/admin/groups', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const perms = await fetch(base + '/admin/permissions', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const users = await fetch(base + '/admin/users', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const subsAdmin = await fetch(base + '/submissions', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const subsReviewer = await fetch(base + '/submissions', { headers: { Authorization: 'Bearer ' + reviewerToken, 'X-Edition-Id': '1' } }).then(r => r.json());
  const customA = await fetch(base + '/plugins/customA', { headers: { Authorization: 'Bearer ' + adminToken, 'X-Edition-Id': '2' } }).then(r => r.json());

